// Writes cars/<slug>.html from car.html, with each car's own title and link preview.
// Run after editing the fleet in assets/js/data.js: node tools/build-pages.mjs
import fs from 'fs';
import { CARS, BUSINESS } from '../assets/js/data.js';
const SITE = 'https://signature-motors-gh.vercel.app';
const root = new URL('..', import.meta.url).pathname;
const tpl = fs.readFileSync(root + 'car.html', 'utf8');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
fs.rmSync(root + 'cars', { recursive: true, force: true });
fs.mkdirSync(root + 'cars');
for (const c of CARS) {
  const title = `${c.year} ${c.name} | Signature Motors`;
  const desc = `Book the ${c.year} ${c.name} for a rental, VIP escort or event in Accra. ${BUSINESS.name}, ${BUSINESS.area}. WhatsApp ${BUSINESS.phoneLabel}.`;
  const url = `${SITE}/cars/${c.slug}`;
  const img = `${SITE}/img/og/${c.slug}.jpg`;
  const meta = `<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${url}">
<meta property="og:type" content="product">
<meta property="og:site_name" content="Signature Motors">
<meta property="og:locale" content="en_GH">
<meta property="og:url" content="${url}">
<meta property="og:title" content="${esc(`${c.year} ${c.name}`)}">
<meta property="og:description" content="${esc(`Rentals · Escorts · Events. Book on WhatsApp ${BUSINESS.phoneLabel}.`)}">
<meta property="og:image" content="${img}">
<meta property="og:image:secure_url" content="${img}">
<meta property="og:image:type" content="image/jpeg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="${esc(`${c.year} ${c.name} from Signature Motors`)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(`${c.year} ${c.name}`)}">
<meta name="twitter:description" content="${esc(`Rentals · Escorts · Events in Accra. WhatsApp ${BUSINESS.phoneLabel}.`)}">
<meta name="twitter:image" content="${img}">
<meta name="theme-color" content="#040404">
<meta name="color-scheme" content="dark">`;
  const html = tpl
    .replace(/<title>[\s\S]*?<meta name="twitter:card"[^>]*>/, meta)
    .replace('<head>', '<head>\n<!-- Generated by tools/build-pages.mjs from car.html. Edit car.html, then rebuild. -->');
  fs.writeFileSync(`${root}cars/${c.slug}.html`, html);
}
console.log(`wrote ${CARS.length} car pages`);
